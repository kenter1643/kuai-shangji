OTHER = "其他"
MAX_TAGS = 3          # 一条记录最多带 3 个行业标签（含主分类）
TITLE_W, BUYER_W = 3, 1


def _score(text: str, weight: int) -> dict[str, int]:
    out: dict[str, int] = {}
    if not text:
        return out
    for cat, rules in CATEGORY_RULES.items():
        s = 0
        for w, kw in rules:
            if kw in text:
                s += w
        if s:
            out[cat] = s * weight
    return out


def classify(title: str = "", buyer: str = "", extra: str = "") -> tuple[str, list[str]]:
    """返回 (主分类, 行业标签列表)。无命中时为 ('其他', ['其他'])。"""
    scores: dict[str, int] = {}
    for text, weight in ((title or "", TITLE_W), (buyer or "", BUYER_W),
                         (extra or "", 1)):
        for cat, s in _score(text, weight).items():
            scores[cat] = scores.get(cat, 0) + s
    if not scores:
        return OTHER, [OTHER]

    ranked = sorted(scores.items(), key=lambda kv: (-kv[1], kv[0]))
    main, top = ranked[0]
    # 主分类必须足够强，否则宁可判「其他」，避免弱词误导筛选
    if top < TITLE_W * 2:
        return OTHER, [OTHER]
    tags = [c for c, s in ranked[:MAX_TAGS] if s >= max(3, top * 0.45)]
    if main not in tags:
        tags.insert(0, main)
    return main, tags[:MAX_TAGS]


def classify_record(rec: dict) -> tuple[str, str]:
    """对一条采集记录分类，返回 (category, categories_json)。"""
    main, tags = classify(rec.get("title") or "", rec.get("buyer") or "",
                          rec.get("agency") or "")
    return main, json.dumps(tags, ensure_ascii=False)


def all_categories() -> list[str]:
    return list(CATEGORY_RULES.keys()) + [OTHER]
